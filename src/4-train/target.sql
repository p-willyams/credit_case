

WITH base_alvo AS (
    SELECT
        s.data_ref,
        s.id_contrato,
        date(s.data_ref)                      AS dt_ref,
        date(s.data_ref, '+12 months')        AS data_fim_janela
    FROM fs_contrato_atual s
    WHERE EXISTS (
            SELECT 1
            FROM base_historico_emprestimos h
            WHERE h.id_contrato = s.id_contrato
              AND h.status_contrato = 'Aprovado'
          )
      AND date(s.data_ref, '+12 months') <= '2025-03-05'
),

alvo AS (
    SELECT
        b.data_ref,
        b.id_contrato,
        MAX(
            CASE
                WHEN date(d.data_prevista_pagamento) < b.data_fim_janela
                 AND (d.data_quitacao IS NULL OR date(d.data_quitacao) > b.dt_ref)
                 AND (d.data_quitacao IS NULL OR date(d.data_quitacao) > date(d.data_prevista_pagamento))
                THEN CAST(
                        julianday(
                            MIN(COALESCE(date(d.data_quitacao), b.data_fim_janela),
                                b.data_fim_janela)
                        ) - julianday(date(d.data_prevista_pagamento))
                     AS INTEGER)
                ELSE 0
            END
        ) AS maximo_dias_atraso_12m
    FROM base_alvo b
    JOIN dividas.base_dividas d ON d.id_contrato = b.id_contrato
    GROUP BY b.data_ref, b.id_contrato
)



